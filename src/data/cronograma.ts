/** Treinos da semana de uma data (semana do mês = 1 a 4; dias 29–31 contam como semana 4).
 *  O cronograma se repete todo ano, mês a mês. */
export function treinosDaSemana(d: Date): Treino[] {
  const semana = Math.min(4, Math.ceil(d.getDate() / 7));
  return CRONOGRAMA.filter((t) => t.mes === d.getMonth() + 1 && t.semana === semana);
}
export const treinoDoDia = (d: Date) => treinosDaSemana(d).find((t) => t.dia === d.getDay()) ?? null;
